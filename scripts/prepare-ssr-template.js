/**
 * Post-build script: reads dist/index.html and writes it as an importable
 * TypeScript module so the SSR function can embed it.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, '..');

const html = readFileSync(resolve(root, 'dist/index.html'), 'utf-8');

mkdirSync(resolve(root, 'api/_lib'), { recursive: true });

writeFileSync(
  resolve(root, 'api/_lib/html-template.ts'),
  `// Auto-generated by scripts/prepare-ssr-template.js — do not edit\nexport const HTML_TEMPLATE = ${JSON.stringify(html)};\n`,
);

console.log('[prepare-ssr-template] Wrote api/_lib/html-template.ts');
